"""Canonical per-landmark facial depth, in bizygomatic-width units.

One number per MediaPipe landmark: how far that point sits in front of (or
behind) the face plane on an average face, expressed as a fraction of the
bizygomatic width so it is scale-free.

Why this table exists
---------------------
De-rotating a face into the frontal plane needs a depth for every landmark.
MediaPipe emits a per-image ``z``, but the audit (docs/FEATURE_AUDIT.md 5.2,
5.3, 5.7) found it is 92.5% canonical template, its residual failed outright
when read as a feature, and using it costs intra-patient reliability: ICC over
the validated features drops to 0.316, *below* the 0.369 of not correcting pose
at all. Substituting this fixed table restores ICC to 0.386 while keeping ~90%
of the pose decontamination.

The table is the per-landmark median of the de-rotated z over the 4559 GMDB
images, each normalized by its own bizygomatic width. It leans on MediaPipe's
z only through a median over thousands of faces, which is exactly the stable
92.5% component; nothing per-image survives.

Regenerate with ``experiments/feature_audit/run_pose_arms.py``.
"""
